'use strict';

/**
 * ПУНКТИ СПИСКУ СЛУЖІННЯ.
 *
 * Список — це впорядкована послідовність пунктів двох типів (пісня й
 * примітка), і тримає її **динамічна зона** `list.points` у
 * `src/components/list/`. Програш — не третій тип, а примітка з ознакою
 * `sounding`: у зібранні під неї крутиться луп.
 *
 * ─── СТАРИЙ КОМПОНЕНТ ПРОГРАША ─────────────────────────────────────────────
 * `list.interlude-point` лишається в зоні до кінця міграції й нічим уже не
 * пишеться: клієнт читає його як примітку зі `sounding` і на першому ж
 * збереженні списку переводить у нову форму. Знімається окремим кроком.
 *
 * ─── ЧОМУ ЗОНА, А НЕ JSON ──────────────────────────────────────────────────
 * Перша версія тримала пункти саморобною структурою в JSON-полі, а поруч жила
 * реляція `songs` — і той самий факт «пісня X у цьому списку» був записаний
 * двічі. Динамічна зона знімає це **структурно**: посилання на пісню тут і є
 * реляцією, тож дзеркалити нема чого.
 *
 * Заразом зникло все, що доводилось писати руками:
 *   валідація типів і довжин  → схема компонентів;
 *   актуальна назва пісні     → populate (перейменування підхоплюється саме);
 *   порядок                   → сама зона;
 *   цілісність                → справжній зовнішній ключ.
 * І адмінка Strapi нарешті вміє правити список — раніше там був непрозорий JSON.
 *
 * ─── ЩО ЛИШИЛОСЬ РУКАМИ ────────────────────────────────────────────────────
 * Рівно одне: видалення пісні **занулює** реляцію в компоненті, а не прибирає
 * сам компонент. Тому пісенний пункт без пісні відсіюється на віддачі — інакше
 * у служінні лишався б порожній рядок.
 *
 * ─── РЕЛЯЦІЯ `list.songs` ──────────────────────────────────────────────────
 * ЗАСТАРІЛА й більше не пишеться. Лишається тимчасово як **джерело міграції**
 * для препроду й проду (`scripts/backfill-list-points.js`); коли вони
 * переїдуть — атрибут прибирається зі схеми.
 */

/** Populate, при якому пункти приїжджають зі своїм вмістом. */
const POINT_POPULATE = { points: { populate: '*' } };

const SONG_POINT = 'list.song-point';

/**
 * Пункти, готові до віддачі клієнту.
 *
 * Єдина ручна дія — прибрати пісенні пункти, що лишились без пісні (її
 * видалили з бібліотеки). Решту зона віддає як є.
 */
const readPoints = (list) =>
  (list?.points ?? []).filter(
    (point) => point.__component !== SONG_POINT || point.song != null
  );

module.exports = {
  POINT_POPULATE,
  SONG_POINT,
  readPoints,
};
